import { ITEM_TYPE } from '../lib/examConstants.js'

const L = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I', 'J']

let _id = 1000
const nid = () => ++_id

function bank(texts, baseId) {
  return texts.map((text, i) => ({
    id: baseId + i,
    label: L[i] || String(i + 1),
    text,
    isLocked: false,
    lockedByItemId: null,
  }))
}

function mcqOptions(texts, baseId) {
  return texts.map((text, i) => ({
    id: baseId + i,
    label: L[i] || String(i + 1),
    text,
  }))
}

function gapItems(count, startNum, baseId) {
  return Array.from({ length: count }, (_, i) => ({
    id: baseId + i,
    itemTypeId: ITEM_TYPE.GapFill,
    displayNumber: startNum + i,
    blankIndex: i,
    promptText: null,
    usesExclusiveOptions: true,
  }))
}

function matchItems(texts, startNum, baseId) {
  return texts.map((promptText, i) => ({
    id: baseId + i,
    itemTypeId: ITEM_TYPE.Matching,
    displayNumber: startNum + i,
    promptText,
    usesExclusiveOptions: true,
  }))
}

function mcqItems(prompts, startNum, baseId, optTexts) {
  return prompts.map((promptText, i) => ({
    id: baseId + i,
    itemTypeId: ITEM_TYPE.McqAbcd,
    displayNumber: startNum + i,
    promptText,
    usesExclusiveOptions: false,
    options: mcqOptions(optTexts[i] || optTexts[0], baseId + 100 + i * 10),
  }))
}

function yesNoItems(prompts, startNum, baseId) {
  return prompts.map((promptText, i) => ({
    id: baseId + i,
    itemTypeId: ITEM_TYPE.YesNo,
    displayNumber: startNum + i,
    promptText,
  }))
}

function tfngItems(prompts, startNum, baseId) {
  return prompts.map((promptText, i) => ({
    id: baseId + i,
    itemTypeId: ITEM_TYPE.TrueFalseNg,
    displayNumber: startNum + i,
    promptText,
    pinPassage: true,
  }))
}

